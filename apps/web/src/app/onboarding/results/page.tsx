import type { Metadata } from "next";
import { useLocale, useTranslations } from "next-intl";
import { getTranslations } from "next-intl/server";
import Link from "next/link";
import { FocusHeader } from "@/components/layout/focus-header";
import { ButtonLink } from "@/components/ui/button";
import { Icon } from "@/components/ui/icon";
import { Avatar, CheckItem, Eyebrow } from "@/components/ui/primitives";
import { cn } from "@/lib/cn";
import { intlTags } from "@/i18n/config";
import { cefrLevels, currentStudent, getTeacher, ratingText, type Specialty, type Teacher } from "@/lib/mock-data";

export async function generateMetadata(): Promise<Metadata> {
  const t = await getTranslations("onboarding.results");
  return { title: t("metaTitle") };
}

// Sample placement result — replaced by the level-test API.
const result = { level: "B1" as const, label: "intermediate" as const };
const skills: { name: "grammar" | "reading" | "listening" | "speaking"; level: string; pct: number; weak?: boolean }[] = [
  { name: "grammar", level: "B1", pct: 55 },
  { name: "reading", level: "B2", pct: 70 },
  { name: "listening", level: "B1", pct: 50 },
  { name: "speaking", level: "A2", pct: 35, weak: true },
];

/** Why a teacher was matched (generated by the matching logic, so translated here). */
type Reason =
  | { id: "specialist"; specialty: Specialty }
  | { id: "experience"; years: number }
  | { id: "evenings" | "speaksSpanish" | "negotiation" | "weekend" | "fluency" | "budget" };

const matches: { slug: string; reasons: Reason[] }[] = [
  {
    slug: "sarah-mitchell",
    reasons: [{ id: "specialist", specialty: "Business English" }, { id: "evenings" }, { id: "speaksSpanish" }],
  },
  {
    slug: "michael-brooks",
    reasons: [{ id: "negotiation" }, { id: "experience", years: 10 }, { id: "weekend" }],
  },
  {
    slug: "james-robinson",
    reasons: [{ id: "fluency" }, { id: "budget" }, { id: "evenings" }],
  },
];

export default function ResultsPage() {
  const tr = useTranslations("onboarding.results");
  const tg = useTranslations("onboarding.goals");
  const tsk = useTranslations("onboarding.skills");
  const tsp = useTranslations("common.specialties");
  const tc = useTranslations("common.rating");
  const locale = useLocale();
  const levelLabel = tg(`levels.${result.label}`);
  const price = (n: number) =>
    n.toLocaleString(intlTags[locale], { style: "currency", currency: "USD", minimumFractionDigits: Number.isInteger(n) ? 0 : 2 });
  const reasonText = (r: Reason) => {
    if (r.id === "specialist") return tr("reasons.specialist", { specialty: tsp.has(r.specialty) ? tsp(r.specialty) : r.specialty });
    if (r.id === "experience") return tr("reasons.experience", { years: r.years });
    return tr(`reasons.${r.id}`);
  };
  const reached = cefrLevels.indexOf(result.level);
  const recommended = matches.map((m) => ({ ...m, teacher: getTeacher(m.slug) })).filter((m): m is { slug: string; reasons: Reason[]; teacher: Teacher } => Boolean(m.teacher));

  return (
    <>
      <FocusHeader center={tr("step")} right={{ href: "/student", label: tr("dashboard") }} progress={100} />
      <main className="mx-auto flex max-w-[1440px] flex-col gap-8 px-4 py-8 sm:px-6 lg:px-20 lg:py-11">
        {/* Level result */}
        <section className="flex flex-col items-center gap-10 rounded-[28px] bg-white p-6 sm:p-10 lg:flex-row lg:gap-12">
          <div
            className="flex size-[200px] shrink-0 flex-col items-center justify-center gap-1 rounded-full bg-navy text-white shadow-[0_0_0_12px_var(--color-teal-100)]"
            aria-label={tr("levelAria", { level: result.level, label: levelLabel })}
            role="img"
          >
            <span className="font-display text-[64px] leading-none font-extrabold">{result.level}</span>
            <span className="text-[15px] font-semibold text-yellow">{levelLabel}</span>
          </div>

          <div className="flex w-full min-w-0 flex-1 flex-col gap-[18px]">
            <Eyebrow>{tr("eyebrow")}</Eyebrow>
            <h1 className="text-[28px] font-extrabold sm:text-4xl">
              {tr("title", { name: currentStudent.firstName, level: result.level })}
            </h1>
            <p className="max-w-[640px] text-base leading-relaxed text-navy-soft">
              {tr("description")}
            </p>
            <ol className="grid max-w-[640px] grid-cols-6 gap-1.5" aria-label={tr("cefrScale")}>
              {cefrLevels.map((l, i) => (
                <li key={l} className="flex flex-col gap-1.5" aria-current={l === result.level ? "step" : undefined}>
                  <span className={cn("h-2.5 rounded-md", i <= reached ? "bg-teal-dark" : "bg-sand")} />
                  <span className={cn("text-[13px]", l === result.level ? "font-bold text-navy" : "text-muted")}>{l}</span>
                </li>
              ))}
            </ol>
          </div>

          <ul className="flex w-full shrink-0 flex-col gap-3.5 border-line-soft max-lg:border-t max-lg:pt-8 lg:w-[300px] lg:border-s lg:ps-10" aria-label={tr("bySkill")}>
            {skills.map((s) => (
              <li key={s.name} className="flex flex-col gap-1.5">
                <div className="flex justify-between text-sm">
                  <span>{tsk(s.name)}</span>
                  <strong>{s.level}</strong>
                </div>
                <div className="h-2 rounded-md bg-line-soft">
                  <div className={cn("h-2 rounded-md", s.weak ? "bg-orange" : "bg-sky")} style={{ width: `${s.pct}%` }} />
                </div>
              </li>
            ))}
          </ul>
        </section>

        {/* Recommendations */}
        <div className="flex flex-col justify-between gap-4 sm:flex-row sm:items-end">
          <div className="flex flex-col gap-2">
            <h2 className="text-2xl font-extrabold sm:text-[28px]">{tr("recommendedTitle")}</h2>
            <p className="text-base text-navy-soft">{tr("recommendedSubtitle", { goal: tg("goals.business") })}</p>
          </div>
          <Link href="/teachers" className="shrink-0 font-semibold text-teal-dark hover:text-navy">
            {tr("seeAll")}
          </Link>
        </div>

        <div className="grid gap-6 pt-3 md:grid-cols-2 xl:grid-cols-3">
          {recommended.map(({ teacher: t, reasons }, i) => (
            <article key={t.slug} className={cn("relative flex flex-col gap-4 rounded-3xl bg-white p-7", i === 0 && "border-2 border-teal")}>
              {i === 0 && <span className="absolute -top-3.5 start-6 rounded-full bg-teal-dark px-3 py-1.5 text-xs font-bold tracking-[1px] text-white">{tr("bestMatch")}</span>}
              <div className="flex items-center gap-4">
                <Avatar initials={t.initials} tone={t.tone} size={72} />
                <div className="flex flex-col gap-1">
                  <h3 className="text-[19px] font-bold">{t.name}</h3>
                  <span className="inline-flex items-center gap-1 text-sm text-muted">
                    {ratingText(t, tc("new"))} <Icon name="star" size={14} className="text-orange" />
                    <span className="sr-only">{tc("outOf5")}</span> · {tr("perLesson", { price: price(t.priceUsd) })}
                  </span>
                </div>
              </div>
              <ul className="flex flex-col gap-2 text-sm">
                {reasons.map((r) => (
                  <CheckItem key={r.id}>{reasonText(r)}</CheckItem>
                ))}
              </ul>
              <div className="mt-auto flex gap-2.5">
                <ButtonLink
                  href={t.offersTrial ? `/teachers/${t.slug}?type=trial` : `/teachers/${t.slug}`}
                  className="flex-1 px-3"
                  aria-label={t.offersTrial ? tr("bookTrialWith", { name: t.name }) : tr("bookLessonWith", { name: t.name })}
                >
                  {t.offersTrial ? tr("bookTrial") : tr("bookLesson")}
                </ButtonLink>
                <ButtonLink href={`/teachers/${t.slug}`} variant="outline" className="flex-1 px-3" aria-label={tr("profileOf", { name: t.name })}>
                  {tr("profile")}
                </ButtonLink>
              </div>
            </article>
          ))}
        </div>
      </main>
    </>
  );
}
