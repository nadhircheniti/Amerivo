type Option = { code: string; value: string; label: string };

function displayNames(locale: string, type: "region" | "language") {
  try {
    return new Intl.DisplayNames([locale, "en"], { type });
  } catch {
    return null;
  }
}

/**
 * Options for a select: the label is in the visitor's language, the stored value stays the English
 * name (so profiles read the same for everyone, e.g. in the admin space).
 */
function options(codes: string[], locale: string, type: "region" | "language"): Option[] {
  const local = displayNames(locale, type);
  const english = displayNames("en", type);
  const collator = new Intl.Collator(locale);
  return codes.map((code) => ({ code, value: english?.of(code) ?? code, label: local?.of(code) ?? english?.of(code) ?? code })).sort((a, b) => collator.compare(a.label, b.label));
}

export const countryOptions = (locale: string) => options(COUNTRY_CODES, locale, "region");
export const languageOptions = (locale: string) => options(LANGUAGE_CODES, locale, "language");

/** ISO code of an English country name (to pick its dialing code). */
export function countryCodeOf(englishName: string) {
  const english = displayNames("en", "region");
  return COUNTRY_CODES.find((c) => english?.of(c) === englishName) ?? null;
}

/** Best guess of the visitor's country from the browser (e.g. "fr-CH" → CH). */
export function browserCountry(): string | null {
  if (typeof navigator === "undefined") return null;
  for (const tag of navigator.languages ?? [navigator.language]) {
    const region = tag.split("-")[1]?.toUpperCase();
    if (region && DIAL_CODES[region]) return region;
  }
  return null;
}
